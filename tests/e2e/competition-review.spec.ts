import { mkdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { test, expect } from "./fixtures";

test("guided sample creates one persistent task, filters it and exports honest evidence on mobile", async ({ page, request }) => {
  const output = resolve("data/runtime/release-2026-10-23/ui"); mkdirSync(output, { recursive: true });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("button", { name: "예제 문서로 시작", exact: true })).toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "작업을 불러오고 있습니다" })).toHaveCount(0);
  await page.screenshot({ path: resolve(output, "desktop-dashboard.png"), fullPage: true, caret: "initial" });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: resolve(output, "mobile-dashboard.png"), fullPage: true, caret: "initial" });
  const before = (await (await request.get("/api/tasks")).json()).tasks.length;
  await page.getByRole("button", { name: "예제 문서로 시작", exact: true }).click();
  await expect(page.getByLabel("새 업무 목표")).toHaveValue(/참가자 명단/);
  await expect(page.getByRole("status").filter({ hasText: "training-notice.txt" })).toBeVisible();
  await expect(page).toHaveURL("/");
  expect((await (await request.get("/api/tasks")).json()).tasks.length).toBe(before);
  await page.getByRole("button", { name: "시작", exact: true }).click();
  await expect(page).toHaveURL(/\/tasks\/[0-9a-f-]{36}$/, { timeout: 45_000 });
  const id = page.url().split("/").at(-1)!;
  expect((await (await request.get("/api/tasks")).json()).tasks.length).toBe(before + 1);
  await expect(page.getByRole("button", { name: "검증 요약 저장" })).toBeVisible();
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "검증 요약 저장" }).click();
  const download = await downloaded; const path = resolve(output, "sample-evidence.json"); await download.saveAs(path);
  const evidence = JSON.parse(readFileSync(path, "utf8"));
  expect(evidence.task.id).toBe(id); expect(evidence.summary.recordedModelCalls).toBe(0);
  expect(evidence.summary.fixtureEpisodes).toBeGreaterThan(0);
  expect(evidence.summary.pendingRequirements).toBeGreaterThan(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.goto("/");
  await page.getByLabel("작업 검색").fill("존재하지않는작업-qa-2026");
  await expect(page.getByText("검색한 작업을 찾지 못했어요.")).toBeVisible();
  await page.getByRole("button", { name: "전체 작업 보기" }).click();
  await page.getByRole("group", { name: "작업 상태 필터" }).getByRole("button", { name: /확인 필요/ }).click();
  await expect(page.locator(`a[href="/tasks/${id}"]`)).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: resolve(output, "desktop-dashboard-active.png"), fullPage: true, caret: "initial" });
  expect(errors).toEqual([]);
});
