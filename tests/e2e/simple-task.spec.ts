import {resolve} from 'node:path';
import {mkdirSync} from 'node:fs';
import {test,expect} from './fixtures';
test('simple task UI handles inline approvals, verified downloads, completion and a narrow screen',async({page})=>{
  const output=resolve('data/runtime/release-2026-10-23/ui');mkdirSync(output,{recursive:true});
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('navigation',{name:'주 메뉴'}).getByRole('link')).toHaveCount(3);
  await page.screenshot({path:resolve(output,'desktop-tasks.png'),caret:'initial'});
  await page.getByLabel('새 업무 목표').fill('교육 대상자 명단과 회신 자료를 준비해줘.');
  await page.getByLabel('업무에 첨부할 파일').setInputFiles(resolve('data/demo/training-notice.txt'));
  await page.getByRole('button',{name:'시작',exact:true}).click();await expect(page).toHaveURL(/\/tasks\/[0-9a-f-]{36}$/);
  const id=page.url().split('/').at(-1)!;
  await page.getByLabel('데모 역할').selectOption('APPROVER');
  const approval=page.locator('#task-approval');await expect(approval.getByRole('checkbox')).toBeEnabled();await approval.getByRole('checkbox').check();await approval.getByRole('button',{name:'승인하고 계속'}).click();
  await expect(approval.getByRole('button',{name:'확인하고 계속'})).toBeVisible();await approval.getByRole('checkbox').check();await approval.getByRole('button',{name:'확인하고 계속'}).click();
  const complete=page.getByRole('region',{name:'완료 조건'});await expect(page.getByRole('link',{name:'파일 받기'})).toHaveCount(2);
  await expect.poll(async()=>(await(await page.request.get(`/api/tasks/${id}`)).json()).task.status).toBe('WAITING_EVENT');
  await expect(complete.getByRole('button',{name:'결과 확인하고 완료'})).toBeDisabled();
  for(const checkbox of await complete.getByRole('checkbox').all())await checkbox.check();
  await expect(complete.getByRole('button',{name:'결과 확인하고 완료'})).toBeEnabled();
  await expect(page.getByRole('link',{name:'완료 조건 확인'})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:resolve(output,'desktop-task.png'),fullPage:true,caret:'initial'});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:resolve(output,'mobile-task.png'),fullPage:true,caret:'initial'});
  await complete.getByRole('button',{name:'결과 확인하고 완료'}).click();
  await expect.poll(async()=>(await(await page.request.get(`/api/tasks/${id}`)).json()).task.status).toBe('COMPLETED');
  expect((await(await page.request.get(`/api/tasks/${id}/triggers`)).json()).triggers.every((trigger:{enabled:boolean})=>!trigger.enabled)).toBe(true);
  expect(errors).toEqual([]);
});
