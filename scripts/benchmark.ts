import "../lib/config/load-env";
import { resolve } from "node:path";
import { runBenchmark } from "../lib/benchmark/runner";
import { renderBenchmark, writeBenchmarkReport } from "../lib/benchmark/report";
import { DEFAULT_NVIDIA_MODEL } from "../lib/providers/presets";
import type { ProviderId } from "../lib/domain/types";
const args = process.argv.slice(2);
const option = (name: string, fallback: string) => { const index = args.indexOf(name); return index < 0 ? fallback : args[index + 1] ?? fallback; };
const provider = option("--provider", "demo") as ProviderId;
if (!["demo", "nebius"].includes(provider)) throw new Error("Unknown benchmark provider");
const runs = Number(option("--runs", "20"));
if (!Number.isInteger(runs) || runs < 20) throw new Error("Competition benchmark requires at least 20 runs per mode");
const keys = { demo: undefined, nebius: process.env.NEBIUS_API_KEY };
const defaults = { demo: "actflow-demo-v1", nebius: DEFAULT_NVIDIA_MODEL };
if (provider === "demo") process.env.ACTFLOW_TEST_MODE = "true";
const report = await runBenchmark({ runs, provider, model: option("--model", defaults[provider]), effort: option("--effort", "default"), allowReal: args.includes("--real"), apiKey: keys[provider] });
const paths = await writeBenchmarkReport(report, resolve(process.env.ACTFLOW_DATA_DIR ?? "data/runtime", "benchmarks"));
console.log(renderBenchmark(report)); console.log(`Raw data: ${paths.json}\nReport: ${paths.markdown}`);
if (report.rawRuns.some(run => !run.completed || !run.verificationPassed || !run.rollbackPassed || !run.extractionPassed)) process.exitCode = 1;
